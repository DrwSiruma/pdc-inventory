<?php

/*
|--------------------------------------------------------------------------
| Common Helper Functions
|--------------------------------------------------------------------------
| Reusable helper functions used throughout the system.
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/config.php';

/*
|--------------------------------------------------------------------------
| Clean Input
|--------------------------------------------------------------------------
*/

function cleanInput($data)
{
    return htmlspecialchars(trim($data), ENT_QUOTES, 'UTF-8');
}

/*
|--------------------------------------------------------------------------
| Redirect
|--------------------------------------------------------------------------
*/

function redirect($path)
{
    header('Location: ' . BASE_URL . $path);
    exit();
}

/*
|--------------------------------------------------------------------------
| Format Date
|--------------------------------------------------------------------------
*/

function formatDate($date)
{
    return date(DATE_FORMAT, strtotime($date));
}

/*
|--------------------------------------------------------------------------
| Format Date & Time
|--------------------------------------------------------------------------
*/

function formatDateTime($date)
{
    return date(DATE_FORMAT . ' ' . TIME_FORMAT, strtotime($date));
}

/*
|--------------------------------------------------------------------------
| Generate Reference Number
|--------------------------------------------------------------------------
|
| Example:
| ACC-20260720-0001
|--------------------------------------------------------------------------
*/

function generateReferenceNo($prefix, $number)
{
    return strtoupper($prefix) . '-' . date('Ymd') . '-' . str_pad($number, 4, '0', STR_PAD_LEFT);
}