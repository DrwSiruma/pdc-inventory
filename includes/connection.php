<?php

/*
|--------------------------------------------------------------------------
| Database Connection
|--------------------------------------------------------------------------
| This file establishes the MySQL database connection.
|--------------------------------------------------------------------------
*/

require_once 'config.php';

/*
|--------------------------------------------------------------------------
| Create Database Connection
|--------------------------------------------------------------------------
*/

$conn = new mysqli(
    DB_HOST,
    DB_USER,
    DB_PASS,
    DB_NAME
);

/*
|--------------------------------------------------------------------------
| Check Connection
|--------------------------------------------------------------------------
*/

if ($conn->connect_error) {
    die('Database connection failed.');
}

/*
|--------------------------------------------------------------------------
| Character Set
|--------------------------------------------------------------------------
*/

$conn->set_charset('utf8mb4');